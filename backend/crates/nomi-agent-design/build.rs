//! Builds the registry of Sora's design library from its folders, so a skill is added by adding
//! `library/<area>/<skill>/SKILL.md` (and any `references/*.md` beside it), never by editing a
//! list. The skills are compiled in with `include_str!`; `src/library.rs` includes the result.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn dirs(path: &Path) -> Vec<PathBuf> {
    let mut found: Vec<PathBuf> = fs::read_dir(path).map(|entries| entries.filter_map(|e| e.ok()).map(|e| e.path()).filter(|p| p.is_dir()).collect()).unwrap_or_default();
    found.sort();
    found
}

fn markdown_files(path: &Path) -> Vec<PathBuf> {
    let mut found: Vec<PathBuf> = fs::read_dir(path)
        .map(|entries| entries.filter_map(|e| e.ok()).map(|e| e.path()).filter(|p| p.extension().is_some_and(|x| x == "md")).collect())
        .unwrap_or_default();
    found.sort();
    found
}

fn name(path: &Path) -> String {
    path.file_stem().unwrap().to_string_lossy().into_owned()
}

fn main() {
    let library = Path::new(&std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("library");
    println!("cargo:rerun-if-changed={}", library.display());
    let mut out = String::from("/// Every skill in the library, by area and then name (generated by build.rs).\npub static LIBRARY: &[Skill] = &[\n");
    for area in dirs(&library) {
        println!("cargo:rerun-if-changed={}", area.display());
        for skill in dirs(&area) {
            println!("cargo:rerun-if-changed={}", skill.display());
            let skill_md = skill.join("SKILL.md");
            if !skill_md.is_file() {
                continue;
            }
            println!("cargo:rerun-if-changed={}", skill_md.display());
            let mut references = String::new();
            let refs = skill.join("references");
            println!("cargo:rerun-if-changed={}", refs.display());
            for reference in markdown_files(&refs) {
                println!("cargo:rerun-if-changed={}", reference.display());
                write!(references, "Reference {{ name: {:?}, text: include_str!({:?}) }}, ", name(&reference), reference.display().to_string()).unwrap();
            }
            writeln!(
                out,
                "    Skill {{ area: {:?}, name: {:?}, text: include_str!({:?}), references: &[{references}] }},",
                area.file_name().unwrap().to_string_lossy(),
                skill.file_name().unwrap().to_string_lossy(),
                skill_md.display().to_string()
            )
            .unwrap();
        }
    }
    out.push_str("];\n");
    fs::write(Path::new(&std::env::var("OUT_DIR").unwrap()).join("library.rs"), out).unwrap();
}
