// ------------------------------------------------------------------------------------- colour

/** '#rrggbb' / '#rgb' / '#rrggbbaa' -> ARGB as a plain number (0xAARRGGBB, never negative). */
export function parseHex(text) {
  const m = /^#([0-9a-fA-F]+)$/.exec(text.trim());
  if (!m) throw new Error(`not a hex colour: ${text}`);
  let digits = m[1];
  if (digits.length === HEX_DIGITS_RGB_SHORT) {
    digits = [...digits].map((d) => (parseInt(d, HEX_RADIX) * NIBBLE_REPEAT).toString(HEX_RADIX).padStart(2, '0')).join('');
  }
  if (digits.length !== HEX_DIGITS_RGB && digits.length !== HEX_DIGITS_RGBA) throw new Error(`unsupported hex colour: ${text}`);
  const rgb = parseInt(digits.slice(FIRST, HEX_DIGITS_RGB), HEX_RADIX);
  const alpha = digits.length === HEX_DIGITS_RGBA ? parseInt(digits.slice(HEX_DIGITS_RGB), HEX_RADIX) : ALPHA_OPAQUE;
  return alpha * BYTE_RANGE ** 3 + rgb;
}

function channels(argb) {
  return [Math.floor(argb / BYTE_RANGE ** 2) % BYTE_RANGE, Math.floor(argb / BYTE_RANGE) % BYTE_RANGE, argb % BYTE_RANGE];
}

/** color-mix(in srgb, A p%, B): per-channel mix in sRGB space, rounded; opaque result. */
export function resolveColorMix(a, percentOfA, b) {
  const weight = percentOfA / PERCENT_SCALE;
  const [ar, ag, ab] = channels(parseHex(a));
  const [br, bg, bb] = channels(parseHex(b));
  const mix = (x, y) => Math.round(x * weight + y * (1 - weight));
  return ALPHA_OPAQUE * BYTE_RANGE ** 3 + mix(ar, br) * BYTE_RANGE ** 2 + mix(ag, bg) * BYTE_RANGE + mix(ab, bb);
}

const COLOR_MIX = /^color-mix\(\s*in\s+srgb\s*,\s*(#[0-9a-fA-F]+)\s+([\d.]+)%\s*,\s*(#[0-9a-fA-F]+)\s*\)$/;

/** Resolves var(--x) against `vars` (raw strings), then color-mix, to an ARGB number. */
function resolveColor(raw, vars, trail = []) {
  const substituted = raw.replace(/var\(\s*(--[\w-]+)\s*\)/g, (_, name) => {
    if (trail.includes(name)) throw new Error(`var() cycle through ${name}`);
    if (!(name in vars)) throw new Error(`unresolved ${name} in "${raw}"`);
    return resolveColorText(vars[name], vars, [...trail, name]);
  });
  const mix = COLOR_MIX.exec(substituted.trim());
  if (mix) return resolveColorMix(mix[1], Number(mix[2]), mix[3]);
  return parseHex(substituted);
}

// var() substitution needs text, so a resolved var that was itself a mix is re-expressed as hex.
function resolveColorText(raw, vars, trail) {
  const argb = resolveColor(raw, vars, trail);
  return `#${(argb % BYTE_RANGE ** 3).toString(HEX_RADIX).padStart(HEX_DIGITS_RGB, '0')}`;
}

// ----------------------------------------------------------------------------------- CSS parse

function stripComments(css) {
  return css.replace(/\/\*[\s\S]*?\*\//g, '');
}

/** Flat list of {selector, decls} for every rule, descending into @media but tagging it. */
function readRules(css, inMedia = false) {
  const rules = [];
  let i = FIRST;
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < FIRST) break;
    const head = css.slice(i, open).trim();
    let depth = 1;
    let j = open + 1;
    while (j < css.length && depth > FIRST) {
      if (css[j] === '{') depth++;
      else if (css[j] === '}') depth--;
      j++;
    }
    const body = css.slice(open + 1, j - 1);
    if (head.startsWith('@')) {
      rules.push(...readRules(body, true).map((r) => ({ ...r, inMedia: true })));
    } else {
      rules.push({ selector: head, inMedia, decls: readDecls(body) });
    }
    i = j;
  }
  return rules;
}

function readDecls(body) {
  const decls = {};
  for (const m of body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) decls[m[1]] = m[2].trim();
  return decls;
}

const SEL_BASE = /^:root$/;
const SEL_DARK = /^:root\[data-theme=['"]dark['"]\]$/;
const SEL_ACCENT = /^:root\[data-color=['"]([\w-]+)['"]\]$/;
const SEL_ACCENT_DARK = /^:root\[data-color=['"]([\w-]+)['"]\]\[data-theme=['"]dark['"]\]$/;

function camel(text) {
  return text.replace(/-(\w)/g, (_, c) => c.toUpperCase());
}

function pickRoles(vars) {
  const roles = {};
  for (const [name, raw] of Object.entries(vars)) {
    let key = null;
    if (name.startsWith(COLOR_ROLE_PREFIX)) key = name.slice(COLOR_ROLE_PREFIX.length);
    else if (name in NOMI_ROLES) key = NOMI_ROLES[name];
    if (key !== null) roles[key] = resolveColor(raw, vars);
  }
  return roles;
}

export function parseGradient(raw, onRaw) {
  const m = /^linear-gradient\(\s*(-?[\d.]+)deg\s*,([\s\S]+)\)$/.exec(raw.trim());
  if (!m) throw new Error(`unsupported gradient: ${raw}`);
  const parts = m[2].split(/,(?![^(]*\))/).map((p) => p.trim());
  const stops = parts.map((part, index) => {
    const s = /^(#[0-9a-fA-F]+)(?:\s+([\d.]+)%)?$/.exec(part);
    if (!s) throw new Error(`unsupported gradient stop: ${part}`);
    const position = s[2] !== undefined ? Number(s[2]) / PERCENT_SCALE : index / (parts.length - 1);
    return [position, parseHex(s[1])];
  });
  const gradient = { angle: Number(m[1]), stops };
  if (onRaw !== undefined) gradient.onColor = parseHex(onRaw);
  return gradient;
}

export function parseMotion(raw) {
  const m = /^(\d+)ms\s+cubic-bezier\(\s*([\d.-]+)\s*,\s*([\d.-]+)\s*,\s*([\d.-]+)\s*,\s*([\d.-]+)\s*\)$/.exec(raw.trim());
  if (!m) throw new Error(`unsupported motion token: ${raw}`);
  return { durationMs: Number(m[1]), x1: Number(m[2]), y1: Number(m[3]), x2: Number(m[4]), y2: Number(m[5]) };
}

/**
 * Parses material3.css into { green:{light,dark}, <accent>:{light,dark}, gradients, motion }.
 *
 * Cascade, as the browser applies it: base `:root` < `:root[data-theme=dark]` < accent light
 * block < accent dark block (dark = all four, light = base + accent light). Every palette is
 * therefore complete. The `prefers-color-scheme` media blocks repeat the data-theme values for
 * the OS-driven case and are skipped. var()/color-mix are resolved after the merge, so e.g.
 * surface-container-lowest mixes the accent's own primary.
 */
export function parseCss(css) {
  const rules = readRules(stripComments(css)).filter((r) => !r.inMedia);
  const base = {};
  const dark = {};
  const accents = {};
  const accent = (name) => (accents[name] ??= { light: {}, dark: {} });
  for (const { selector, decls } of rules) {
    let m;
    if (SEL_BASE.test(selector)) Object.assign(base, decls);
    else if (SEL_DARK.test(selector)) Object.assign(dark, decls);
    else if ((m = SEL_ACCENT.exec(selector))) Object.assign(accent(m[1]).light, decls);
    else if ((m = SEL_ACCENT_DARK.exec(selector))) Object.assign(accent(m[1]).dark, decls);
  }

  const out = { [DEFAULT_ACCENT]: { light: pickRoles(base), dark: pickRoles({ ...base, ...dark }) } };
  for (const [name, { light, dark: accentDark }] of Object.entries(accents)) {
    out[name] = {
      light: pickRoles({ ...base, ...light }),
      dark: pickRoles({ ...base, ...dark, ...light, ...accentDark }),
    };
  }

  out.gradients = {};
  out.motion = {};
  for (const [name, raw] of Object.entries(base)) {
    if (name.startsWith(GRADIENT_PREFIX)) {
      const tone = name.slice(GRADIENT_PREFIX.length);
      if (tone !== ACTION_GRADIENT) out.gradients[camel(tone)] = parseGradient(raw, base[ON_GRADIENT_PREFIX + tone]);
    } else if (name.startsWith(MOTION_PREFIX)) {
      out.motion[camel(name.slice(MOTION_PREFIX.length))] = parseMotion(raw);
    }
  }
  out.typescale = parseTypescale(base);
  out.corners = {};
  out.bubbles = {};
  for (const [name, raw] of Object.entries(base)) {
    if (name.startsWith(CORNER_PREFIX)) out.corners[camel(name.slice(CORNER_PREFIX.length))] = parsePx(raw);
    else if (name.startsWith(BUBBLE_PREFIX)) out.bubbles[camel(name.slice(BUBBLE_PREFIX.length))] = parseCorners(raw);
  }
  return out;
}

/** '12px' / '0' -> number of px. */
export function parsePx(raw) {
  const m = /^(-?[\d.]+)(px)?$/.exec(raw.trim());
  if (!m) throw new Error(`unsupported px length: ${raw}`);
  return Number(m[1]);
}

/** CSS border-radius shorthand with four values -> [topLeft, topRight, bottomRight, bottomLeft]. */
export function parseCorners(raw) {
  const parts = raw.trim().split(/\s+/).map(parsePx);
  if (parts.length !== CORNER_SIDES) throw new Error(`expected ${CORNER_SIDES} corner values: ${raw}`);
  return parts;
}

/** A CSS length in rem/em/px/0 -> rem; `sizeRem` converts em. */
function toRem(raw, sizeRem) {
  const m = /^(-?[\d.]+)(rem|em|px)?$/.exec(raw.trim());
  if (!m) throw new Error(`unsupported length: ${raw}`);
  const n = Number(m[1]);
  if (m[2] === 'em') return n * sizeRem;
  if (m[2] === 'px') return n / PX_PER_REM;
  return n;
}

const FAMILY_NAMES = ['brand', 'title', 'plain', 'mono'];

/** Follows var() hops from a -font property to the --md-ref-typeface-<family> it names. */
function familyOf(vars, name) {
  const raw = vars[name]?.trim() ?? '';
  const m = /^var\(\s*(--[\w-]+)\s*\)$/.exec(raw);
  if (!m) throw new Error(`${name}: expected var(--md-ref-typeface-*), got "${raw}"`);
  if (m[1].startsWith(TYPEFACE_PREFIX)) {
    const family = m[1].slice(TYPEFACE_PREFIX.length);
    if (!FAMILY_NAMES.includes(family)) throw new Error(`${name}: unknown family ${family}`);
    return family;
  }
  return familyOf(vars, m[1]);
}

/**
 * Every --md-sys-typescale-<role> (incl. emphasized-<role>) as
 * { family, weight, sizeSp, lineHeightSp, trackingEm }, var() resolved, rem -> sp at 16px/rem.
 */
export function parseTypescale(vars) {
  const resolve = (raw, trail = []) =>
    raw.replace(/var\(\s*(--[\w-]+)\s*\)/g, (_, name) => {
      if (trail.includes(name)) throw new Error(`var() cycle through ${name}`);
      if (!(name in vars)) throw new Error(`unresolved ${name} in "${raw}"`);
      return resolve(vars[name], [...trail, name]);
    });
  const roles = new Set();
  for (const name of Object.keys(vars)) {
    if (name.startsWith(TYPESCALE_PREFIX) && name.endsWith('-font')) roles.add(name.slice(TYPESCALE_PREFIX.length, -'-font'.length));
  }
  const out = {};
  for (const role of roles) {
    const get = (field) => {
      const name = `${TYPESCALE_PREFIX}${role}-${field}`;
      if (!(name in vars)) throw new Error(`${name} is missing`);
      return resolve(vars[name]).trim();
    };
    const [, weight, size, lineHeight, tracking] = TYPESCALE_FIELDS.map((field) => (field === 'font' ? '' : get(field)));
    const family = familyOf(vars, `${TYPESCALE_PREFIX}${role}-font`);
    const sizeRem = toRem(size);
    out[camel(role)] = {
      family,
      weight: Number(weight),
      sizeSp: sizeRem * PX_PER_REM,
      lineHeightSp: toRem(lineHeight) * PX_PER_REM,
      trackingEm: toRem(tracking, sizeRem) / sizeRem,
    };
  }
  return out;
}

// ---------------------------------------------------------------------------------- shapes.ts

/** Evaluates `-Math.PI / 2` style expressions: numbers, Math.PI, unary minus, * and /. */
function evalPhase(expr) {
  const tokens = expr.match(/Math\.PI|\d+(?:\.\d+)?|[*/-]|\S/g) ?? [];
  let pos = FIRST;
  const unary = () => {
    const t = tokens[pos++];
    if (t === '-') return -unary();
    if (t === 'Math.PI') return Math.PI;
    if (t !== undefined && /^\d/.test(t)) return Number(t);
    throw new Error(`unsupported token "${t}" in shape phase "${expr}"`);
  };
  let value = unary();
  while (pos < tokens.length) {
    const op = tokens[pos++];
    if (op !== '*' && op !== '/') throw new Error(`unsupported operator "${op}" in shape phase "${expr}"`);
    const rhs = unary();
    value = op === '*' ? value * rhs : value / rhs;
  }
  return value;
}

function braceBody(src, from) {
  const open = src.indexOf('{', from);
  let depth = 1;
  let i = open + 1;
  while (i < src.length && depth > FIRST) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}') depth--;
    i++;
  }
  return src.slice(open + 1, i - 1);
}

export function parseShapes(src) {
  const start = /const SPECS\b[^=]*=/.exec(src);
  if (!start) throw new Error('SPECS not found in shapes.ts');
  const body = braceBody(src, start.index + start[FIRST].length);
  const specs = {};
  for (const m of body.matchAll(/(['"]?)([\w-]+)\1\s*:\s*\{([^}]*)\}/g)) {
    const field = (name) => new RegExp(`${name}\\s*:\\s*([^,}]+)`).exec(m[3])?.[1].trim();
    const lobes = field('lobes');
    const amplitude = field('amplitude');
    const phase = field('phase');
    if (lobes === undefined || amplitude === undefined) throw new Error(`shape ${m[2]} lacks lobes/amplitude`);
    specs[m[2]] = { lobes: evalPhase(lobes), amplitude: evalPhase(amplitude), phase: phase === undefined ? 0 : evalPhase(phase) };
  }
  return specs;
}

export function parseShapeConstants(src) {
  const read = (name) => {
    const m = new RegExp(`const ${name}\\s*=\\s*([\\d.]+)`).exec(src);
    if (!m) throw new Error(`${name} not found in shapes.ts`);
    return Number(m[1]);
  };
  return { points: read('POINTS'), radius: read('RADIUS'), center: read('CENTER') };
}

// ------------------------------------------------------------------------------------- Kotlin

const kLong = (n) => `0x${n.toString(HEX_RADIX).toUpperCase().padStart(HEX_DIGITS_RGBA, '0')}L`;
const kFloat = (n) => {
  const text = String(Number(n.toPrecision(9)));
  return `${text.includes('.') || text.includes('e') ? text : `${text}.0`}f`;
};
const kString = (s) => JSON.stringify(s);

function emitRoles(roles, requiredKeys, indent) {
  const missing = requiredKeys.filter((k) => !(k in roles));
  if (missing.length) throw new Error(`palette lacks roles: ${missing.join(', ')}`);
  const pad = KOTLIN_INDENT.repeat(indent);
  return `NomiRoles(\n${requiredKeys.map((k) => `${pad}${KOTLIN_INDENT}${camel(k)} = ${kLong(roles[k])},`).join('\n')}\n${pad})`;
}

/** Builds the whole NomiTokens.kt text from the CSS and shapes.ts on disk (or the given text). */
export function emitKotlin(css = readFileSync(CSS_PATH, 'utf8'), shapesSrc = readFileSync(SHAPES_PATH, 'utf8')) {
  const tokens = parseCss(css);
  const { gradients, motion, typescale, corners, bubbles } = tokens;
  const palettes = Object.entries(tokens).filter(([name]) => !EXTRA_KEYS.includes(name));
  const roleKeys = Object.keys(tokens[DEFAULT_ACCENT].light);
  const specs = parseShapes(shapesSrc);
  const consts = parseShapeConstants(shapesSrc);

  for (const [agent, look] of Object.entries(AGENT_LOOKS)) {
    if (!(look.shape in specs)) throw new Error(`agent ${agent}: shape ${look.shape} is not in shapes.ts SPECS`);
    if (!(look.tone in gradients)) throw new Error(`agent ${agent}: tone ${look.tone} is not a gradient in material3.css`);
  }

  const roleFields = roleKeys.map((k) => `${KOTLIN_INDENT}val ${camel(k)}: Long,`).join('\n');
  const paletteEntries = palettes
    .map(
      ([name, p]) =>
        `${KOTLIN_INDENT}${KOTLIN_INDENT}${kString(name)} to NomiPalette(\n` +
        `${KOTLIN_INDENT.repeat(3)}light = ${emitRoles(p.light, roleKeys, 3)},\n` +
        `${KOTLIN_INDENT.repeat(3)}dark = ${emitRoles(p.dark, roleKeys, 3)},\n` +
        `${KOTLIN_INDENT}${KOTLIN_INDENT}),`,
    )
    .join('\n');

  const gradientVals = Object.entries(gradients)
    .map(([name, g]) => {
      const stops = g.stops.map(([pos, color]) => `${kFloat(pos)} to ${kLong(color)}`).join(', ');
      return `${KOTLIN_INDENT}val ${name} = GradientSpec(angleDeg = ${kFloat(g.angle)}, stops = listOf(${stops}), onColor = ${kLong(g.onColor)})`;
    })
    .join('\n');
  const gradientAll = Object.keys(gradients).map((n) => `${kString(n)} to ${n}`).join(', ');

  const motionVals = Object.entries(motion)
    .map(
      ([name, m]) =>
        `${KOTLIN_INDENT}val ${name} = MotionSpec(durationMs = ${m.durationMs}, x1 = ${kFloat(m.x1)}, y1 = ${kFloat(m.y1)}, x2 = ${kFloat(m.x2)}, y2 = ${kFloat(m.y2)})`,
    )
    .join('\n');

  const shapeEntries = Object.entries(specs)
    .map(([name, s]) => `${KOTLIN_INDENT.repeat(2)}${kString(name)} to PolarSpec(lobes = ${s.lobes}, amplitude = ${kFloat(s.amplitude)}, phase = ${kFloat(s.phase)}),`)
    .join('\n');
  const agentShape = Object.entries(AGENT_LOOKS).map(([a, l]) => `${kString(a)} to ${kString(l.shape)}`).join(', ');
  const agentTone = Object.entries(AGENT_LOOKS).map(([a, l]) => `${kString(a)} to ${kString(l.tone)}`).join(', ');

  const typescaleVals = Object.entries(typescale)
    .map(
      ([name, t]) =>
        `${KOTLIN_INDENT}val ${name} = TypeRole(family = ${kString(t.family)}, weight = ${t.weight}, sizeSp = ${kFloat(t.sizeSp)}, lineHeightSp = ${kFloat(t.lineHeightSp)}, trackingEm = ${kFloat(t.trackingEm)})`,
    )
    .join('\n');
  const cornerVals = Object.entries(corners).map(([n, px]) => `${KOTLIN_INDENT}const val ${n} = ${kFloat(px)}`).join('\n');
  const bubbleVals = Object.entries(bubbles)
    .map(([n, [tl, tr, br, bl]]) => `${KOTLIN_INDENT}val bubble${n[0].toUpperCase()}${n.slice(1)} = CornerSpec(topStart = ${kFloat(tl)}, topEnd = ${kFloat(tr)}, bottomEnd = ${kFloat(br)}, bottomStart = ${kFloat(bl)})`)
    .join('\n');

  return `${HEADER}
package ${KOTLIN_PACKAGE}

/** Every colour role is opaque-or-not ARGB (0xAARRGGBB) in a Long. */
data class NomiRoles(
${roleFields}
)

data class NomiPalette(val light: NomiRoles, val dark: NomiRoles)

data class GradientSpec(val angleDeg: Float, val stops: List<Pair<Float, Long>>, val onColor: Long)

data class MotionSpec(val durationMs: Int, val x1: Float, val y1: Float, val x2: Float, val y2: Float)

data class PolarSpec(val lobes: Int, val amplitude: Float, val phase: Float)

/** [family] is one of "brand" | "title" | "plain" | "mono"; sizes in sp (16px per rem), tracking in em. */
data class TypeRole(val family: String, val weight: Int, val sizeSp: Float, val lineHeightSp: Float, val trackingEm: Float)

/** Per-corner radii in dp, already resolved for start-to-end layout. */
data class CornerSpec(val topStart: Float, val topEnd: Float, val bottomEnd: Float, val bottomStart: Float)

object NomiPalettes {
    const val DEFAULT_ACCENT = ${kString(DEFAULT_ACCENT)}

    val all: Map<String, NomiPalette> = mapOf(
${paletteEntries}
    )
}

object NomiGradients {
${gradientVals}

    val all: Map<String, GradientSpec> = mapOf(${gradientAll})
}

object NomiMotionTokens {
${motionVals}
}

object NomiTypescale {
${typescaleVals}
}

object NomiCorners {
${cornerVals}

${bubbleVals}
}

const val SHAPE_POINTS = ${consts.points}
const val SHAPE_RADIUS = ${kFloat(consts.radius)}
const val SHAPE_CENTER = ${kFloat(consts.center)}

object NomiShapeSpecs {
    val all: Map<String, PolarSpec> = mapOf(
${shapeEntries}
    )

    val agentShape: Map<String, String> = mapOf(${agentShape})
    val agentTone: Map<String, String> = mapOf(${agentTone})
}
`;
}

// ---------------------------------------------------------------------------------------- CLI

function main(argv) {
  const generated = emitKotlin();
  if (argv.includes('--check')) {
    const committed = existsSync(OUT_PATH) ? readFileSync(OUT_PATH, 'utf8') : null;
    if (committed === generated) return 0;
    console.error(`${relative(ROOT_DIR, OUT_PATH)} is stale. Run: node native/scripts/gen-tokens.mjs and commit the result.`);
    return 1;
  }
  mkdirSync(dirname(OUT_PATH), { recursive: true });
  writeFileSync(OUT_PATH, generated);
  console.log(`wrote ${relative(ROOT_DIR, OUT_PATH)}`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) process.exit(main(process.argv.slice(2)));
