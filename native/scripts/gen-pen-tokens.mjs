#!/usr/bin/env node
// Turns frontend-new's pen tokens into Kotlin constants for the Compose design system, so the native
// apps draw with the same colours, type, spacing and radii as the web app.
//
//   node native/scripts/gen-pen-tokens.mjs           write NomiPenTokens.kt
//   node native/scripts/gen-pen-tokens.mjs --check   exit 1 when the committed file is stale (CI)
//
// Sources: frontend-new/src/lib/ds/tokens/tokens.json (exported from Nomi.pen) and the @theme block
// of frontend-new/src/app.css (line heights, tracking and the radii only the web names).
// No dependencies; the generated Kotlin uses plain Long/Int/Float/String types (no Compose).

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseHex } from './gen-tokens.mjs';

const HEADER = '// Generated by native/scripts/gen-pen-tokens.mjs from frontend-new tokens.json and app.css. Do not edit.';
const KOTLIN_PACKAGE = 'ai.nomi.designsystem.generated';
const INDENT = '    ';
const HEX_RADIX = 16;
const ARGB_DIGITS = 8;
const NO_TRACKING = 0;

const ROOT_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const TOKENS_PATH = resolve(ROOT_DIR, 'frontend-new/src/lib/ds/tokens/tokens.json');
const APP_CSS_PATH = resolve(ROOT_DIR, 'frontend-new/src/app.css');
const OUT_PATH = resolve(
  ROOT_DIR,
  'native/shared/designsystem/src/commonMain/kotlin/ai/nomi/designsystem/generated/NomiPenTokens.kt',
);

const PEN_PREFIX = 'nm-';
const CREW_PREFIX = 'crew-';
const SPACE_PREFIX = 'nm-space-';
const CREW_BG = '-bg';
const CREW_INK = '-ink';

/** The web's type roles, by their --text-* name. */
const TYPE_ROLES = ['display', 'heading', 'body', 'ui', 'caption', 'label', 'micro', 'nano', 'phone-title', 'phone', 'phone-sm', 'phone-large', 'phone-display'];
/** The web's radii, by their --radius-* name. */
const RADII = ['hair', 'cell', '2xs', 'xs', 'sm', 'tile', 'inner', 'md'];

/** tokens.json → colours as {light, dark} ARGB, numbers and strings, each by token name. */
export function parsePenTokens(jsonText) {
  const { tokens } = JSON.parse(jsonText);
  const colors = {};
  const numbers = {};
  const strings = {};
  for (const [name, token] of Object.entries(tokens)) {
    if (token.type === 'color') {
      const light = parseHex(token.light ?? token.value);
      const dark = parseHex(token.dark ?? token.value);
      colors[name] = { light, dark };
    } else if (token.type === 'number') {
      numbers[name] = token.value;
    } else if (token.type === 'string') {
      strings[name] = token.value;
    }
  }
  return { colors, numbers, strings };
}

function themeBlock(cssText) {
  const start = cssText.indexOf('@theme');
  if (start < 0) throw new Error('app.css has no @theme block');
  const open = cssText.indexOf('{', start);
  let depth = 0;
  for (let i = open; i < cssText.length; i++) {
    if (cssText[i] === '{') depth++;
    if (cssText[i] === '}' && --depth === 0) return cssText.slice(open + 1, i).replace(/\/\*[\s\S]*?\*\//g, '');
  }
  throw new Error('app.css @theme block is not closed');
}

function declarations(block) {
  const out = {};
  for (const m of block.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) out[m[1]] = m[2].trim();
  return out;
}

/** A px length, or var(--nm-…) resolved against tokens.json's numbers. */
function pixels(value, numbers, what) {
  const ref = /^var\(--([\w-]+)\)$/.exec(value);
  if (ref) {
    if (!(ref[1] in numbers)) throw new Error(`${what}: ${value} is not a number token`);
    return numbers[ref[1]];
  }
  const px = /^(-?[\d.]+)px$/.exec(value);
  if (!px) throw new Error(`${what}: ${value} is not a px length`);
  return Number(px[1]);
}

/** app.css @theme → type roles (size, line height, tracking in px) and radii in px. */
export function parseThemeScale(cssText, { numbers }) {
  const decls = declarations(themeBlock(cssText));
  const type = {};
  for (const role of TYPE_ROLES) {
    const size = decls[`--text-${role}`];
    const lineHeight = decls[`--text-${role}--line-height`];
    if (!size || !lineHeight) throw new Error(`app.css has no --text-${role} size and line height`);
    // Only the role's own letter-spacing: a --tracking-* is a separate utility a component opts into.
    const tracking = decls[`--text-${role}--letter-spacing`];
    type[kotlinName(role)] = {
      size: pixels(size, numbers, `--text-${role}`),
      lineHeight: pixels(lineHeight, numbers, `--text-${role}--line-height`),
      tracking: tracking ? pixels(tracking, numbers, `tracking of ${role}`) : NO_TRACKING,
    };
  }
  const radius = {};
  for (const name of RADII) {
    const value = decls[`--radius-${name}`];
    if (!value) throw new Error(`app.css has no --radius-${name}`);
    radius[kotlinName(name)] = pixels(value, numbers, `--radius-${name}`);
  }
  const tracking = {};
  for (const [prop, value] of Object.entries(decls)) {
    const name = /^--tracking-([\w-]+)$/.exec(prop);
    if (name) tracking[kotlinName(name[1])] = pixels(value, numbers, prop);
  }
  return { type, radius, tracking };
}

/** kebab-case → camelCase, a leading count moved to the end: 2xs → xs2, text-3 → text3. */
function kotlinName(kebab) {
  const lead = /^(\d+)(.*)$/.exec(kebab);
  const name = lead ? `${lead[2]}${lead[1]}` : kebab;
  return name.replace(/-(\w)/g, (_, c) => c.toUpperCase());
}

function argb(value) {
  return `0x${value.toString(HEX_RADIX).toUpperCase().padStart(ARGB_DIGITS, '0')}L`;
}

function float(n) {
  return `${n}f`;
}

/** The tokens and scale → the Kotlin source of NomiPenTokens.kt. */
export function emitPenKotlin({ colors, numbers, strings }, { type, radius, tracking }) {
  const pen = Object.keys(colors).filter((n) => n.startsWith(PEN_PREFIX));
  const crewNames = Object.keys(colors)
    .filter((n) => n.startsWith(CREW_PREFIX) && !n.endsWith(CREW_BG) && !n.endsWith(CREW_INK))
    .map((n) => n.slice(CREW_PREFIX.length));
  const field = (n) => kotlinName(n.slice(PEN_PREFIX.length));
  const scheme = (which) => pen.map((n) => `${INDENT}${INDENT}${field(n)} = ${argb(colors[n][which])},`).join('\n');
  const crew = crewNames.map((c) => {
    const base = colors[`${CREW_PREFIX}${c}`];
    const bg = colors[`${CREW_PREFIX}${c}${CREW_BG}`];
    const ink = colors[`${CREW_PREFIX}${c}${CREW_INK}`];
    if (!bg || !ink) throw new Error(`crew ${c} needs ${CREW_PREFIX}${c}${CREW_BG} and ${CREW_PREFIX}${c}${CREW_INK}`);
    return `${INDENT}${INDENT}"${c}" to CrewColors(${argb(base.light)}, ${argb(bg.light)}, ${argb(bg.dark)}, ${argb(ink.light)}, ${argb(ink.dark)}),`;
  });
  const space = Object.keys(numbers)
    .filter((n) => n.startsWith(SPACE_PREFIX))
    .map((n) => `${INDENT}const val ${kotlinName(n.slice(SPACE_PREFIX.length))} = ${numbers[n]}`);
  const radii = Object.entries(radius).map(([n, v]) => `${INDENT}const val ${n} = ${v}`);
  const trackings = Object.entries(tracking).map(([n, v]) => `${INDENT}const val ${n} = ${float(v)}`);
  const roles = Object.entries(type).map(([n, r]) => `${INDENT}val ${n} = PenTypeRole(${float(r.size)}, ${float(r.lineHeight)}, ${float(r.tracking)})`);

  return [
    HEADER,
    `package ${KOTLIN_PACKAGE}`,
    '',
    '/** Every pen colour as ARGB (0xAARRGGBB) in a Long, named as on the web without the nm- prefix. */',
    'data class PenColors(',
    pen.map((n) => `${INDENT}val ${field(n)}: Long,`).join('\n'),
    ')',
    '',
    'object NomiPenColors {',
    `${INDENT}val light = PenColors(`,
    scheme('light'),
    `${INDENT})`,
    `${INDENT}val dark = PenColors(`,
    scheme('dark'),
    `${INDENT})`,
    '}',
    '',
    '/** A crew member\'s colours: the mascot\'s own, and its tinted ground and ink per scheme. */',
    'data class CrewColors(val base: Long, val bgLight: Long, val bgDark: Long, val inkLight: Long, val inkDark: Long)',
    '',
    'object NomiCrewColors {',
    `${INDENT}val all: Map<String, CrewColors> = mapOf(`,
    crew.join('\n'),
    `${INDENT})`,
    '}',
    '',
    '/** The pen spacing scale in dp. */',
    'object NomiPenSpace {',
    space.join('\n'),
    '}',
    '',
    '/** The web\'s radii in dp. */',
    'object NomiPenRadius {',
    radii.join('\n'),
    '}',
    '',
    '/** A type role: size and line height in sp, tracking in px (sp on native). */',
    'data class PenTypeRole(val size: Float, val lineHeight: Float, val trackingPx: Float)',
    '',
    'object NomiPenType {',
    roles.join('\n'),
    '}',
    '',
    '/** The web\'s tracking-* utilities in px (sp on native), applied only where a component names one. */',
    'object NomiPenTracking {',
    trackings.join('\n'),
    '}',
    '',
    'object NomiPenFonts {',
    `${INDENT}const val SANS = "${strings['nm-sans']}"`,
    `${INDENT}const val MONO = "${strings['nm-mono']}"`,
    '}',
    '',
  ].join('\n');
}

function generate() {
  const tokens = parsePenTokens(readFileSync(TOKENS_PATH, 'utf8'));
  return emitPenKotlin(tokens, parseThemeScale(readFileSync(APP_CSS_PATH, 'utf8'), tokens));
}

function main(argv) {
  const kotlin = generate();
  if (argv.includes('--check')) {
    const current = existsSync(OUT_PATH) ? readFileSync(OUT_PATH, 'utf8') : '';
    if (current !== kotlin) {
      console.error('NomiPenTokens.kt is stale: run node native/scripts/gen-pen-tokens.mjs');
      return 1;
    }
    return 0;
  }
  mkdirSync(dirname(OUT_PATH), { recursive: true });
  writeFileSync(OUT_PATH, kotlin);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) process.exit(main(process.argv.slice(2)));
