import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parsePenTokens, parseThemeScale, emitPenKotlin } from './gen-pen-tokens.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const tokensJson = readFileSync(resolve(ROOT, 'frontend-new/src/lib/ds/tokens/tokens.json'), 'utf8');
const appCss = readFileSync(resolve(ROOT, 'frontend-new/src/app.css'), 'utf8');

test('a two-scheme colour parses to light and dark ARGB', () => {
  const { colors } = parsePenTokens(tokensJson);
  assert.deepEqual(colors['nm-bg'], { light: 0xfff6f6f4, dark: 0xff0a0a0b });
});

test('an RGBA hex becomes ARGB with its alpha first', () => {
  const { colors } = parsePenTokens(tokensJson);
  assert.equal(colors['nm-danger-bg'].light, 0x0dc93c32);
});

test('a single-value colour is the same in both schemes', () => {
  const { colors } = parsePenTokens(tokensJson);
  assert.deepEqual(colors['crew-nomi'], { light: 0xff61d192, dark: 0xff61d192 });
});

test('numbers and strings are kept by name', () => {
  const { numbers, strings } = parsePenTokens(tokensJson);
  assert.equal(numbers['nm-space-xl'], 16);
  assert.equal(strings['nm-sans'], 'Geist');
});

test('the type scale resolves var() sizes against the tokens', () => {
  const scale = parseThemeScale(appCss, parsePenTokens(tokensJson));
  assert.deepEqual(scale.type.body, { size: 15, lineHeight: 19, tracking: 0 });
});

test('a role carries only its own letter-spacing; tracking utilities stay separate', () => {
  const scale = parseThemeScale(appCss, parsePenTokens(tokensJson));
  assert.equal(scale.type.display.tracking, -0.4);
  assert.deepEqual(scale.type.phoneLarge, { size: 32, lineHeight: 42, tracking: 0 });
  assert.equal(scale.type.label.tracking, 0);
  assert.equal(scale.tracking.phoneLarge, -0.6);
  assert.equal(scale.tracking.label, 0.6);
});

test('radii resolve, including the ones only app.css names', () => {
  const scale = parseThemeScale(appCss, parsePenTokens(tokensJson));
  assert.equal(scale.radius.tile, 7);
  assert.equal(scale.radius.sm, 6);
  assert.equal(scale.radius.md, 10);
});

test('the emitted Kotlin carries the header and resolved values only', () => {
  const tokens = parsePenTokens(tokensJson);
  const kt = emitPenKotlin(tokens, parseThemeScale(appCss, tokens));
  assert.ok(kt.startsWith('// Generated by native/scripts/gen-pen-tokens.mjs'));
  assert.match(kt, /val bg: Long/);
  assert.match(kt, /bg = 0xFFF6F6F4L/);
  assert.match(kt, /"sora" to CrewColors\(/);
  assert.match(kt, /val phoneLarge = PenTypeRole\(32f, 42f, 0f\)/);
  assert.match(kt, /const val phoneLarge = -0\.6f/);
  assert.doesNotMatch(kt, /var\(/);
});

test('every type role and radius app.css declares is read, not a fixed list', () => {
  const scale = parseThemeScale(appCss, parsePenTokens(tokensJson));
  assert.deepEqual(scale.type.phoneAction, { size: 18, lineHeight: 23, tracking: 0 });
  assert.equal(scale.radius.sheet, 22);
  assert.equal(scale.radius.lg, 12);
  assert.equal(scale.radius.agenda, 6.5);
});

test('shadows keep their offset, blur and which pen colour they cast', () => {
  const scale = parseThemeScale(appCss, parsePenTokens(tokensJson));
  assert.deepEqual(scale.shadow.float, { x: 0, y: 8, blur: 24, color: 'shadow' });
  assert.deepEqual(scale.shadow.focus, { x: 0, y: 0, blur: 8, color: 'focus' });
  const tokens = parsePenTokens(tokensJson);
  const kt = emitPenKotlin(tokens, scale);
  assert.match(kt, /val float = PenShadow\(0f, 8f, 24f, "shadow"\)/);
  assert.match(kt, /const val agenda = 6\.5f/);
});
